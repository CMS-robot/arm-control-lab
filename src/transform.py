"""transform.py —— 三维旋转矩阵（SO(3)）的基础积木。

━━━ 项目级约定（整个仓库统一，后面所有模块都按这个来）━━━

    · 坐标系   : 右手系。x 向前、y 向左、z 向上（FR3 基座坐标，右手中指→食指→拇指）
    · 向量     : 列向量，形状 (3,) 存一个点，(N, 3) 存一堆点
    · 变换写法 : v_new = R @ v      ← 左乘！不是 v @ R
    · 角度单位 : 弧度（rad）        ← 不是度！传度进来不会报错，只会算出垃圾

━━━ 这个文件提供什么 ━━━

    三个"造旋转矩阵"的函数 :

        rot_x(t)  绕 x 轴转 t 弧度 -> 3x3 矩阵
        rot_y(t)  绕 y 轴转 t 弧度 -> 3x3 矩阵
        rot_z(t)  绕 z 轴转 t 弧度 -> 3x3 矩阵

    一个"检查"函数 :

        is_rotation(R)   R 到底是不是一个合法的旋转矩阵？

    转轴方向用右手定则判断：右手大拇指指向 +x（或 +y / +z），
    四指弯曲的方向就是正的旋转方向（逆时针）。

"""

import numpy as np


# ============================================================
# 三个旋转矩阵
# ============================================================


def rot_x(t: float) -> np.ndarray:
    """绕 x 轴旋转 t 弧度（主动旋转，右手定则）。

    返回的矩阵长这样，其中 c = cos(t)、s = sin(t)：

        [[1.0, 0.0, 0.0],
         [0.0,   c,  -s],
         [0.0,   s,   c]]

    逐行解释（这就是"为什么长这样"）：

        第 1 行 [1, 0, 0]  -> 新 x 完全来自旧 x，其他不掺和
                              >>> 这就是"绕 x 轴转"的标志：转轴上那一个分量不变
        第 2 行 [0, c,-s]  -> 新 y = c*旧y - s*旧z
        第 3 行 [0, s, c]  -> 新 z = s*旧y + c*旧z
                              （y、z 两个方向互相"漏"一点过去，所以是把
                               yz 平面整个转了一下）

    怎么用：v_new = rot_x(t) @ v

        例：rot_x(pi/2) @ [0, 1, 0] -> [0, 0, 1]   （y 轴被转到 z 轴）
        例：rot_x(pi/2) @ [0, 0, 1] -> [0, -1, 0]  （z 轴被转到 -y 方向）

    参数
        t : float，旋转角，单位【弧度】

    返回
        np.ndarray，形状 (3, 3)，dtype float64
        t = 0 时结果等于 np.eye(3)（单位阵）

    注意
        传"度"进来不会报错 —— rot_x(90) 是合法的，算出来是垃圾。
        要传度必须先 np.radians(90)，这是本项目最容易犯的错，没有之一。
    """
    # 一次把 cos / sin 算出来，后面每一格直接填这两个变量。

    c = np.cos(t)
    s = np.sin(t)

    # 数字统一写成 0.0 / 1.0，不写整数 0 / 1，原因：
    #   1) 一眼看出这是浮点矩阵，不会被误当成整数矩阵
    #   2) dtype 习惯 —— 往后做数组运算时，整数数组会坑人（比如整数除法），

    return np.array([
        [1.0, 0.0, 0.0],   # 第 1 行：x 不动 -> 绕的就是 x 轴
        [0.0,   c,  -s],   # 第 2 行：新 y = c*y - s*z
        [0.0,   s,   c],   # 第 3 行：新 z = s*y + c*z
    ])


def rot_y(t: float) -> np.ndarray:
    """绕 y 轴旋转 t 弧度（主动旋转，右手定则）。

    返回的矩阵长这样，其中 c = cos(t)、s = sin(t)：

        [[  c, 0.0,   s],
         [0.0, 1.0, 0.0],
         [ -s, 0.0,   c]]

    逐行解释：

        第 1 行 [c, 0, s]    -> 新 x = c*旧x + s*旧z
        第 2 行 [0, 1, 0]    -> 新 y 完全来自旧 y
                                >>> 这就是"绕 y 轴转"的标志
        第 3 行 [-s, 0, c]   -> 新 z = -s*旧x + c*旧z

    ⚠️ 三个函数里就数它最容易写反 ——
       rot_x / rot_z 的规律是"上面一行先出 -s"，而 rot_y 是"上面一行
       先出 +s、下面一行才是 -s"。写反了矩阵照样是合法旋转矩阵，
       is_rotation 也查不出来（它就是转了反方向），只能靠测试里的
       方向用例（test_rot_y_90deg_maps_z_to_x）抓出来。

    怎么用：v_new = rot_y(t) @ v

        例：rot_y(pi/2) @ [0, 0, 1] -> [1, 0, 0]   （z 轴被转到 x 轴）

    参数
        t : float，旋转角，单位【弧度】

    返回
        np.ndarray，形状 (3, 3)，dtype float64
    """
    c = np.cos(t)
    s = np.sin(t)

    return np.array([
        [   c, 0.0,   s],   # 第 1 行：新 x = c*x + s*z
        [ 0.0, 1.0, 0.0],   # 第 2 行：y 不动 -> 绕的就是 y 轴
        [  -s, 0.0,   c],   # 第 3 行：新 z = -s*x + c*z
    ])


def rot_z(t: float) -> np.ndarray:
    """绕 z 轴旋转 t 弧度（主动旋转，右手定则）。

    返回的矩阵长这样，其中 c = cos(t)、s = sin(t)：

        [[  c,  -s, 0.0],
         [  s,   c, 0.0],
         [0.0, 0.0, 1.0]]

    逐行解释：

        第 1 行 [c, -s, 0]   -> 新 x = c*旧x - s*旧y
        第 2 行 [s,  c, 0]   -> 新 y = s*旧x + c*旧y
                                （xy 平面转了一下，这就是"绕 z 轴转"）
        第 3 行 [0, 0, 1]    -> 新 z 完全来自旧 z，不动 >>> 绕的就是 z 轴

    这是机器人里用得最多的一个（关节轴大多朝上/朝下，绕 z 转），
    D14 要画的那张"旋转几何图"就是它：把单位圆上的点做 rot_z，
    点会沿着圆周跑。

    怎么用：v_new = rot_z(t) @ v

        例：rot_z(pi/2) @ [1, 0, 0] -> [≈0, 1, 0]  （x 轴被转到 y 轴）
            注意是"≈0"而不是"0" —— 实跑出来是 [6.123234e-17, 1.0, 0.0]，
            因为 cos(pi/2) 在浮点里不是精确的 0。比较时一律用 np.allclose。

    参数
        t : float，旋转角，单位【弧度】

    返回
        np.ndarray，形状 (3, 3)，dtype float64
    """
    c = np.cos(t)
    s = np.sin(t)

    return np.array([
        [   c,  -s, 0.0],   # 第 1 行：新 x = c*x - s*y
        [   s,   c, 0.0],   # 第 2 行：新 y = s*x + c*y
        [ 0.0, 0.0, 1.0],   # 第 3 行：z 不动 -> 绕的就是 z 轴
    ])


# ============================================================
# 检查函数
# ============================================================


def is_rotation(R: np.ndarray, tol: float = 1e-9) -> bool:
    """判断 R 是不是一个合法的 3x3 旋转矩阵。三个条件缺一不可。

    背景：什么样的矩阵才配叫"旋转"？

        旋转有两个必须同时满足的几何性质 ——

        条件 A（正交 / orthogonal）：转完长度不变、夹角不变
            R.T @ R == np.eye(3)
            写成数学式子就是 R^T R = I，等价于 R^-1 = R^T
            （旋转矩阵的逆 = 它的转置，这就是为什么求逆几乎不要钱）
            推论：det(R) = ±1（不做证明，记住结论就行）

        条件 B（右手 / right-handed）：det(R) == +1
            光有 A 不够！行列式为 -1 的正交矩阵是"镜面反射"：
            它也不改变长度、不改变夹角，但把右手变成了左手 ——
            那是照镜子，不是旋转。

    所以三关（按顺序，越便宜的越先查）：

        第 0 关  入口消毒：把任何输入变成 float 数组
        第 1 关  形状关  ：必须是 (3, 3)
        第 2 关  正交关  ：R.T @ R ≈ I
        第 3 关  右手关  ：det(R) ≈ +1

    参数
        R   : np.ndarray（或 list / 任何能转成数组的东西），待检查的矩阵
        tol : float，容差，默认 1e-9。旋转矩阵由 sin/cos 算出来，
              必然带浮点误差，所以不能要求严格相等

    返回
        bool，True = 是合法旋转矩阵，False = 不是

    典型用法
        # 单元测试里自检
        assert is_rotation(rot_z(0.7))
        # 或者以后从 URDF / 标定文件读进来的旋转部分，先过一道安检
        if not is_rotation(R):
            raise ValueError("这个矩阵不是旋转矩阵，检查一下标定数据")
    """
    # ---------- 第 0 关：入口消毒 ----------
    # np.asarray(x, dtype=float) 是项目里所有函数的统一开场白（P2 缺口 3）：
    #   · 传进来是 list        -> 转成数组
    #   · 传进来已经是 float64 数组 -> 原样复用（不复制，零开销）
    #   · dtype 不对（比如整数）->
    # 一行把三种情况全处理掉，后面就可以放心地 .shape / @ / np.linalg 了。
    R = np.asarray(R, dtype=float)

    # ---------- 第 1 关：形状关 ----------
    # 先卡形状再算东西，这样 2x2、4x4、一维向量进来会直接 False，
    # 而不是继续往下走然后在矩阵乘法处抛异常。
    # （本项目只用到 3x3；以后做齐次变换时这里会加一个 4x4 的分支，
    #   到时候记得"别改这个函数，另写一个 is_homogeneous_transform"）
    if R.shape != (3, 3):
        return False

    # ---------- 第 2 关：正交关 ----------
    # R.T @ R 应该等于单位阵。
    # 这里必须显式写 rtol 和 atol 两个参数，不能只写一个 ——
    # np.allclose 的默认值是 rtol=1e-5, atol=1e-8，两个都比我们的 tol=1e-9 松，
    # 只传 atol 的话 rtol 还是 1e-5 在起作用，这个检查就名存实亡了。

    if not np.allclose(R.T @ R, np.eye(3), rtol=tol, atol=tol):
        return False

    # ---------- 第 3 关：右手关 ----------
    # np.linalg.det 算行列式。旋转必须 +1；
    # -1 是镜面反射，其它值说明还有缩放（比如 2*eye(3) 的 det = 8）。
    if not np.isclose(np.linalg.det(R), 1.0, rtol=tol, atol=tol):
        return False

    # 三关全过
    return True


