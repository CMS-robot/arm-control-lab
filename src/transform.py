    print("rot_z(pi/2) =")
    print(np.round(rot_z(np.pi / 2), 12))   #  np.round(a, decimals=0)，四舍五入
    print()
    print("rot_z(pi/2) @ [1,0,0] =", rot_z(np.pi / 2) @ np.array([1.0, 0.0, 0.0]))
    print("三个函数在 t=0 时都等于单位阵 :",
          np.allclose(rot_x(0), np.eye(3)) and
          np.allclose(rot_y(0), np.eye(3)) and
          np.allclose(rot_z(0), np.eye(3)))
    print("is_rotation(rot_z(0.7)) =", is_rotation(rot_z(0.7)))
    print("is_rotation(镜面 diag(1,1,-1)) =", is_rotation(np.diag([1.0, 1.0, -1.0])))
